const theme = (
  typeId: string,
  title: string,
  might: Theme['might'],
  powerTags: [string, string, string],
  weakness: string,
  quest: string,
): Theme => ({
  id: uid('theme'),
  typeId,
  title,
  might,
  powerTags: powerTags.map((tag) => makeTag(tag, 'power')),
  weaknessTags: [makeTag(weakness, 'weakness')],
  quest,
  improve: 0,
  abandon: 0,
  milestone: 0,
  specialImprovements: [],
  specialStates: {},
  pendingImprovements: 0,
  nascentPowerTagsNeeded: 0,
  pendingNascentPowerTags: 0,
});

